/**
 * QMC1：静态 128 字节密钥 XOR。
 *
 * 该变换同时被 QMC2/Map 复用（只是把 128 字节静态表换成压缩后的长密钥）。
 * 无文件头、无尾部、无 ekey，因此只能「先解出前若干字节，再看像不像音频容器」来识别。
 */

/** 上游 `v1/mod.rs` 的静态密钥。 */
export const V1_STATIC_KEY: Uint8Array = Uint8Array.from([
  0xc3, 0x4a, 0xd6, 0xca, 0x90, 0x67, 0xf7, 0x52, 0xd8, 0xa1, 0x66, 0x62, 0x9f, 0x5b, 0x09, 0x00,
  0xc3, 0x5e, 0x95, 0x23, 0x9f, 0x13, 0x11, 0x7e, 0xd8, 0x92, 0x3f, 0xbc, 0x90, 0xbb, 0x74, 0x0e,
  0xc3, 0x47, 0x74, 0x3d, 0x90, 0xaa, 0x3f, 0x51, 0xd8, 0xf4, 0x11, 0x84, 0x9f, 0xde, 0x95, 0x1d,
  0xc3, 0xc6, 0x09, 0xd5, 0x9f, 0xfa, 0x66, 0xf9, 0xd8, 0xf0, 0xf7, 0xa0, 0x90, 0xa1, 0xd6, 0xf3,
  0xc3, 0xf3, 0xd6, 0xa1, 0x90, 0xa0, 0xf7, 0xf0, 0xd8, 0xf9, 0x66, 0xfa, 0x9f, 0xd5, 0x09, 0xc6,
  0xc3, 0x1d, 0x95, 0xde, 0x9f, 0x84, 0x11, 0xf4, 0xd8, 0x51, 0x3f, 0xaa, 0x90, 0x3d, 0x74, 0x47,
  0xc3, 0x0e, 0x74, 0xbb, 0x90, 0xbc, 0x3f, 0x92, 0xd8, 0x7e, 0x11, 0x13, 0x9f, 0x23, 0x95, 0x5e,
  0xc3, 0x00, 0x09, 0x5b, 0x9f, 0x62, 0x66, 0xa1, 0xd8, 0x52, 0xf7, 0x67, 0x90, 0xca, 0xd6, 0x4a,
]);

export const V1_OFFSET_BOUNDARY = 0x7fff;

/**
 * 单字节变换。`offset` 是该字节在（已裁剪的）音频流中的**绝对偏移**。
 *
 * 陷阱：只有 `offset > 0x7FFF` 才取模；`offset === 0x7FFF` 必须保持原值，
 * 上游 `test_decode_boundary` 专门覆盖这一字节。
 */
export function qmc1Transform(key128: Uint8Array, value: number, offset: number): number {
  let off = offset;
  if (off > V1_OFFSET_BOUNDARY) off = off % V1_OFFSET_BOUNDARY;
  return (value ^ key128[off & 0x7f]) & 0xff;
}

/** 原地解密一段数据；`offset` 为这段数据在音频流中的绝对偏移。 */
export function decryptQMC1WithKey(data: Uint8Array, offset: number, key128: Uint8Array): void {
  for (let i = 0; i < data.length; i++) {
    data[i] = qmc1Transform(key128, data[i], offset + i);
  }
}

/** 用内置静态密钥原地解密。 */
export function decryptQMC1(data: Uint8Array, offset = 0): void {
  decryptQMC1WithKey(data, offset, V1_STATIC_KEY);
}

/** 返回解密后的副本（不修改入参，便于探测）。 */
export function decryptQMC1Copy(data: Uint8Array, offset = 0): Uint8Array {
  const out = data.slice();
  decryptQMC1(out, offset);
  return out;
}
